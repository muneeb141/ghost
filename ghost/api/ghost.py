import time
import uuid

import frappe
import frappe.rate_limiter
from frappe import _
from frappe.utils import now_datetime


@frappe.whitelist(allow_guest=True, methods=["POST"])
@frappe.rate_limiter.rate_limit(limit=100, seconds=3600)
def create_ghost_session(email=None, fingerprint=None):
	"""Create a server-named anonymous identity. Fingerprints are not credentials."""
	settings = frappe.get_single("Ghost Settings")
	if not settings.enable_ghost_feature:
		frappe.throw(_("Ghost feature is disabled"))
	if email:
		frappe.throw(
			_("Ghost identities are generated by the server; email is not accepted"), frappe.PermissionError
		)
	ghost_role = settings.ghost_role or "Ghost"
	if frappe.db.get_value("Role", ghost_role, "desk_access"):
		frappe.throw(_("The anonymous Ghost role must not grant Desk access"), frappe.PermissionError)
	domain = (settings.ghost_email_domain or "guest.local").lower()
	email = f"ghost_{uuid.uuid4().hex}@{domain}"
	user = frappe.get_doc(
		{
			"doctype": "User",
			"email": email,
			"first_name": "Ghost",
			"last_name": "User",
			"send_welcome_email": 0,
			"enabled": 1,
			"user_type": "Website User",
			"roles": [{"role": ghost_role}],
		}
	)
	# A collision must fail; it must never load and authenticate an existing User.
	user.insert(ignore_permissions=True)
	from ghost.api.auth import generate_oauth_tokens

	tokens = generate_oauth_tokens(user.name)
	return {"user": user.name, **tokens, "message": _("Ghost session created")}


@frappe.whitelist(methods=["POST"])
def convert_to_real_user(
	ghost_email,
	real_email,
	first_name=None,
	last_name=None,
	otp_code=None,
	bypass_otp=False,
	conversion_channel="OTP",
):
	"""Public OTP conversion. Provider proofs are accepted only by private server paths."""
	from ghost.ghost.doctype.otp.otp import verify
	from ghost.security import require_owned_ghost

	if not frappe.get_single("Ghost Settings").get("enable_otp_login"):
		frappe.throw(_("OTP login is disabled"), frappe.PermissionError)
	if bypass_otp or conversion_channel != "OTP":
		frappe.throw(_("Verification cannot be bypassed by an API caller"), frappe.PermissionError)
	ghost_email = require_owned_ghost(ghost_email)
	if not otp_code or not real_email:
		frappe.throw(_("Target identity and OTP code are required"))
	phone = real_email.split("@")[0] if real_email.endswith("@mobile.login") else None
	verify(otp_code, email=None if phone else real_email, phone=phone, purpose="Conversion")
	return _convert_verified_user(ghost_email, real_email, first_name, last_name)


def _convert_verified_user(
	ghost_email, real_email, first_name=None, last_name=None, conversion_channel="OTP", issue_tokens=True
):
	"""
	Converts a Ghost User to a Real User using one of two conversion modes:
	- rename: native Frappe rename when target user does not exist
	- manual_migration: app-level migration when target user already exists
	"""
	from ghost.api.auth import generate_oauth_tokens

	total_start = time.monotonic()
	logger = frappe.logger("ghost_conversion")
	settings = frappe.get_single("Ghost Settings")

	from ghost.security import normalize_recipients, require_enabled_user, require_owned_ghost

	ghost_email = require_owned_ghost(ghost_email)
	real_email, _phone = normalize_recipients(real_email)
	if not real_email or real_email == ghost_email or real_email.startswith("ghost_"):
		frappe.throw(_("A non-anonymous target identity is required"), frappe.PermissionError)
	if real_email in ("Administrator", "Guest"):
		frappe.throw(_("Built-in accounts cannot be conversion targets"), frappe.PermissionError)

	existence_start = time.monotonic()
	target_exists = frappe.db.get_value("User", real_email, "name", for_update=True)
	if target_exists:
		require_enabled_user(real_email)
	elif not settings.get("allow_public_signup"):
		frappe.throw(_("Public signup is disabled"), frappe.PermissionError)
	logger.info(
		f"Ghost conversion target existence check duration_ms={(time.monotonic() - existence_start) * 1000:.2f} "
		f"ghost={ghost_email} real={real_email} target_exists={bool(target_exists)}"
	)

	original_user = frappe.session.user
	frappe.set_user("Administrator")
	try:
		token_invalidation_start = time.monotonic()
		# Revocation is mandatory: anonymous credentials must not survive conversion.
		frappe.db.sql(  # nosemgrep: frappe-sql-format-injection - constant parameterized SQL query
			"""
			UPDATE `tabOAuth Bearer Token`
			SET status = 'Revoked'
			WHERE user = %s AND status = 'Active'
		""",
			(ghost_email,),
		)
		logger.info(f"Invalidated ghost tokens for {ghost_email}")
		logger.info(
			f"Ghost conversion token invalidation duration_ms={(time.monotonic() - token_invalidation_start) * 1000:.2f} "
			f"ghost={ghost_email} real={real_email}"
		)

		branch_start = time.monotonic()
		if target_exists:
			migration_stats = migrate_ghost_data_to_existing_user(ghost_email, real_email)
			conversion_mode = "manual_migration"
			merged = False
		else:
			convert_by_rename(ghost_email, real_email)
			migration_stats = {}
			conversion_mode = "rename"
			merged = False
		logger.info(
			f"Ghost conversion branch duration_ms={(time.monotonic() - branch_start) * 1000:.2f} "
			f"ghost={ghost_email} real={real_email} mode={conversion_mode}"
		)
	finally:
		frappe.set_user(original_user)

	role_profile_start = time.monotonic()
	user = frappe.get_doc("User", real_email)
	if not target_exists:
		apply_user_profile_and_roles(user, settings, first_name, last_name)
		user.save(ignore_permissions=True)
	logger.info(
		f"Ghost conversion role/profile update duration_ms={(time.monotonic() - role_profile_start) * 1000:.2f} "
		f"ghost={ghost_email} real={real_email} mode={conversion_mode}"
	)

	token_generation_start = time.monotonic()
	new_tokens = generate_oauth_tokens(real_email) if issue_tokens else None
	logger.info(
		f"Ghost conversion token generation duration_ms={(time.monotonic() - token_generation_start) * 1000:.2f} "
		f"ghost={ghost_email} real={real_email}"
	)

	response = {
		"message": _("User converted successfully"),
		"user": real_email,
		"merged": merged,
		"conversion_mode": conversion_mode,
	}

	if migration_stats:
		response["migration"] = migration_stats

	if new_tokens:
		response.update(
			{
				"access_token": new_tokens["access_token"],
				"refresh_token": new_tokens["refresh_token"],
				"expires_in": new_tokens["expires_in"],
				"token_type": new_tokens["token_type"],
			}
		)

	if getattr(settings, "enable_lead_capture", 0):
		lead_dt = settings.lead_doctype or "Ghost Lead"
		status_field = settings.lead_status_fieldname or "status"
		converted_status = settings.lead_converted_status or "Converted"
		ghost_field = settings.lead_ghost_fieldname or "ghost_email"

		if status_field:
			frappe.db.sql(
				f""" # nosemgrep: frappe-sql-format-injection - dynamic table and column names originate exclusively from validated administrator settings
				UPDATE `tab{lead_dt}`
				SET `{status_field}` = %s
				WHERE `{ghost_field}` IN (%s, %s)
			""",
				(converted_status, ghost_email, real_email),
			)

	# Captured emails/fingerprints are not proof of ownership of other anonymous accounts.
	_log_conversion(
		settings, ghost_email, real_email, conversion_mode, total_start, conversion_channel=conversion_channel
	)

	logger.info(
		f"Ghost conversion total duration_ms={(time.monotonic() - total_start) * 1000:.2f} "
		f"ghost={ghost_email} real={real_email} mode={conversion_mode}"
	)
	if settings.enable_webhooks:
		from ghost.events import on_ghost_converted

		on_ghost_converted(ghost_email, real_email, conversion_mode, new_tokens)
	return response


def convert_by_rename(ghost_email, real_email):
	"""Use Frappe's link-aware rename and preserve the caller's transaction."""
	from frappe.model.rename_doc import rename_doc

	rename_doc("User", ghost_email, real_email, force=True, ignore_permissions=True)


def get_ghost_owned_reassignment_plan():
	"""
	Only includes app-owned doctypes and safe, explicit field updates.
	"""
	return [
		{
			"doctype": "OTP",
			"field": "user",
			"description": "Reassign OTP user reference from ghost to real user",
		},
		{
			"doctype": "OTP",
			"field": "email",
			"description": "Reassign OTP email when it matches ghost email",
		},
	]


def migrate_ghost_data_to_existing_user(ghost_email, real_email):
	migration_counts = {}
	for rule in get_ghost_owned_reassignment_plan():
		count = frappe.db.count(rule["doctype"], filters={rule["field"]: ghost_email})
		if count:
			frappe.db.sql(  # nosemgrep: frappe-sql-format-injection - doctypes and fields are verified internal application schemas
				f"UPDATE `tab{rule['doctype']}` SET `{rule['field']}` = %s WHERE `{rule['field']}` = %s",
				(real_email, ghost_email),
			)
		migration_counts[f"{rule['doctype']}.{rule['field']}"] = count

	# Keep ghost user for audit/history; disable it so it cannot be used after migration.
	frappe.db.set_value("User", ghost_email, "enabled", 0, update_modified=False)
	return migration_counts


def apply_user_profile_and_roles(
	user, settings, first_name=None, last_name=None, conservative_name_update=False
):
	ghost_role = settings.ghost_role or "Ghost"
	target_role = settings.default_user_role
	new_roles = [r for r in user.roles if r.role != ghost_role]
	existing_role_names = [r.role for r in new_roles]

	if target_role and target_role not in existing_role_names:
		if frappe.db.exists("Role", target_role):
			new_roles.append({"doctype": "Has Role", "role": target_role})
		else:
			frappe.log_error(f"Role '{target_role}' not found, skipping role assignment during conversion")

	user.set("roles", new_roles)

	if first_name and (not conservative_name_update or not user.first_name or user.first_name == "Ghost"):
		user.first_name = first_name
	if last_name and (not conservative_name_update or not user.last_name or user.last_name == "User"):
		user.last_name = last_name


def _log_conversion(
	settings, ghost_email, real_email, conversion_mode, total_start, conversion_channel="OTP"
):
	"""Record a successful conversion in Ghost Conversion Log.

	Controlled by the enable_conversion_logging toggle in Ghost Settings.
	Must never break the conversion flow — any failure is logged and swallowed.
	"""
	if not getattr(settings, "enable_conversion_logging", 0):
		return
	try:
		client_info = None
		try:
			if frappe.request and frappe.request.headers:
				client_info = frappe.request.headers.get("User-Agent")
		except Exception:
			# No request context (tests, background jobs) — client info stays empty.
			pass

		frappe.get_doc(
			{
				"doctype": "Ghost Conversion Log",
				"ghost_email": ghost_email,
				"real_email": real_email,
				"conversion_mode": conversion_mode,
				"conversion_channel": conversion_channel,
				"conversion_duration_ms": (time.monotonic() - total_start) * 1000,
				"converted_at": now_datetime(),
				"client_info": client_info,
			}
		).insert(ignore_permissions=True)
	except Exception as e:
		frappe.log_error(f"Failed to log ghost conversion {ghost_email} -> {real_email}: {e!s}")
